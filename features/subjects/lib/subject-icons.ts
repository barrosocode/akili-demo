export const subjectIcons: Record<string, LucideIcon> = {
  "book-open": BookOpen,
  book: Book,
  library: Library,
  languages: Languages,
  "pen-line": PenLine,
  "layout-grid": LayoutGrid,
  calculator: Calculator,
  sigma: Sigma,
  "flask-conical": FlaskConical,
  microscope: Microscope,
  atom: Atom,
  leaf: Leaf,
  "test-tube": TestTube,
  landmark: Landmark,
  globe: Globe,
  map: Map,
  brain: Brain,
  users: Users,
  scale: Scale,
  music: Music,
  palette: Palette,
  dumbbell: Dumbbell,
  "clipboard-list": ClipboardList,
  "graduation-cap": GraduationCap,
  puzzle: Puzzle,
  lightbulb: Lightbulb,
};

export function resolveSubjectIcon(icon: string | null | undefined): LucideIcon {
  const key = icon?.trim().toLowerCase() ?? "";
  return subjectIcons[key] ?? BookOpen;
}
